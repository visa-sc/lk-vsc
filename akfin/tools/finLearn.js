function categorize(name) {
  const n = String(name || "").toLowerCase();
  for (const r of CATEGORY_RULES) for (const m of r.m) if (n.includes(m)) return r.c;
  return "Прочее";
}

function num(s) {
  const t = String(s || "").replace(/[\s ]/g, "").replace(",", ".");
  const v = parseFloat(t);
  return isNaN(v) ? 0 : v;
}

function main() {
  const dir = process.argv[2];
  const monthsWanted = Number(process.argv[3] || 12);
  if (!dir) { console.error("Использование: node tools/finLearn.js <папка-с-csv> [месяцев]"); process.exit(1); }
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".csv"));

  // Берём последние N месячных листов по названию «<Месяц> <Год>-…»
  const dated = [];
  for (const f of files) {
    const m = f.match(/^([А-Яа-яЁё]+) (\d{4})-/);
    if (!m) continue;
    const mi = MONTHS.indexOf(m[1]);
    if (mi < 0) continue;
    dated.push({ f, key: Number(m[2]) * 12 + mi });
  }
  dated.sort((a, b) => b.key - a.key);
  const picked = dated.slice(0, monthsWanted);

  const stat = new Map();
  for (const { f } of picked) {
    const lines = fs.readFileSync(path.join(dir, f), "utf8").split(/\r\n|\r|\n/);
    for (let i = 1; i < lines.length; i++) {
      const c = lines[i].split(";");
      if (c.length < 6) continue;
      const name = (c[1] || "").trim();
      if (!name) continue;
      const vals = [num(c[2]), num(c[3]), num(c[4]), num(c[5])];
      const amt = vals[0] + vals[1] + vals[2] + vals[3];
      if (!amt) continue;                       // заметки без сумм
      if (/^[\d\s.,]+$/.test(name)) continue;   // строка итогов
      const bi = vals.findIndex((v) => v > 0);
      const key = name.toLowerCase().replace(/\s+/g, " ").trim();
      let s = stat.get(key);
      if (!s) { s = { name, n: 0, b: [0, 0, 0, 0], amounts: [] }; stat.set(key, s); }
      s.n++; s.b[bi]++; s.amounts.push(amt);
    }
  }

  const frequent = [...stat.values()]
    .filter((s) => s.n >= 3)
    .sort((a, b) => b.n - a.n)
    .slice(0, 60)
    .map((s) => {
      s.amounts.sort((a, b) => a - b);
      const med = s.amounts[Math.floor(s.amounts.length / 2)];
      return {
        name: s.name.trim(),
        bucket: BUCKETS[s.b.indexOf(Math.max(...s.b))],
        amount: Math.round(med),
        category: categorize(s.name),
        uses: s.n,
      };
    });

  const out = {
    builtAt: new Date().toISOString(),
    monthsAnalyzed: picked.length,
    frequent,
    categoryRules: CATEGORY_RULES,
    categories: [...new Set(CATEGORY_RULES.map((r) => r.c))].concat(["Прочее"]),
  };
  process.stdout.write(JSON.stringify(out, null, 2));
}

main();
module.exports = { categorize, CATEGORY_RULES };
