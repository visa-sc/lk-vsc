// Отдельное письмо Петрову про «Мои eSIM» в боте (Андрей 19.11.2026: «отдельное письмо, чтобы закинул
// в свой Claude и не затёр изменения, 30 ноября в 9 утра»). Петров правит тексты бота через
// esim-bot-texts.json — пусть его Claude знает новые строки и не возвращает старую.
//   cron: 0 9 30 11 *  node tools/petrovBotNotice.js     (шлёт один раз, повторно не шлёт)
//   node tools/petrovBotNotice.js --dry                   — показать, не отправлять
require("dotenv").config({ path: require("path").join(__dirname, "..", ".env"), quiet: true });
const fs = require("fs");
const path = require("path");
const { sendMail } = require("../mail.js");

const DIR = path.join(__dirname, "..", ".esim", "petrov-sync");
const FLAG = path.join(DIR, "bot-notice-sent.json");
const DRY = process.argv.includes("--dry");
const NAME = "ПРАВКИ-бот-Мои-eSIM-19.11.md";

const MD = `# Бот eSIM: изменён раздел «Мои eSIM» (19.11.2026, Андрей Комисаренко)

Для Claude Андрея Петрова. Код бота (tgbot.js) правим мы, вы правите тексты бота через \`esim-bot-texts.json\` (пары «как в коде» → «как показать»). Чтобы не затереть изменения, учтите следующее.

## Что изменилось
Раньше, если у человека в боте не было eSIM, бот писал «Здесь появятся ваши eSIM после первой покупки.» Купившие на сайте не понимали, где их eSIM.

Теперь бот спрашивает почту, ищет по ней eSIM, шлёт на эту почту код из 6 цифр и после кода показывает eSIM в боте. Купленные в боте без почты получают эту почту и видны на сайте. Если по почте ничего нет, бот предлагает проверить почту или открыть кабинет на сайте.

## Новые тексты бота (так написано в коде)
- «Здесь появятся eSIM, купленные в боте.»
- «<b>Покупали на сайте?</b> Напишите почту, на которую пришёл QR-код, и я покажу ваши eSIM здесь.»
- «По почте … eSIM не нашлось.» / «Проверьте, нет ли опечатки, и пришлите почту ещё раз. Или поищите письмо с QR-кодом в почте и посмотрите на сайте:»
- «Нашёл N eSIM на почте …» / «Чтобы чужие не увидели ваши QR-коды, отправил на эту почту код из 6 цифр. Пришлите его сюда.» / «Письмо не пришло? Загляните в «Спам».»
- «Готово, ваши eSIM теперь и в боте, и на сайте.»
- «Код не подошёл. Проверьте и пришлите ещё раз.» / «Код устарел. Пришлите почту ещё раз, отправлю новый.»
- «Слишком много попыток за час. Ваши eSIM можно открыть на сайте по почте:» / «Не получилось отправить код, попробуйте через минуту. Или откройте eSIM на сайте:»
- кнопки: «📱 Мои eSIM на сайте», «🌍 Купить eSIM», «🛟 Поддержка»
- письмо с кодом: тема «Код для бота VOYO mobile: 123456»

## Что сделать
1. В \`esim-bot-texts.json\` строка «Здесь появятся ваши eSIM после первой покупки.» больше не используется, её можно удалить. Не возвращайте этот текст обратно ни в файл, ни в описания бота.
2. Если хотите поменять формулировки новых строк — добавьте пары в \`esim-bot-texts.json\` как обычно. Смысл не менять: шаг с кодом на почту обязателен (защита QR-кодов от чужих).
3. На витрине (esim.html) кнопка «Мои eSIM» в шапке теперь синяя с белым (класс \`mine my\`) — это есть в отдельном письме про правки витрины, при выкладке не затирать.
`;

(async () => {
  if (!DRY && fs.existsSync(FLAG)) return console.log("уже отправлено");
  fs.mkdirSync(DIR, { recursive: true });
  const file = path.join(DIR, NAME);
  fs.writeFileSync(file, MD, "utf8");
  const o = { to: "ap@spt1.ru", replyTo: "director@visa-sc.ru",
    subject: "eSIM: изменён раздел «Мои eSIM» в боте — отдайте файл своему Claude",
    text: "Андрей, добрый день!\n\n19.11 в боте eSIM изменён раздел «Мои eSIM»: купившие на сайте теперь видят свои eSIM в боте после кода с почты. Появились новые тексты бота.\n\n" +
      "Отдайте вложенный файл своему Claude: там список новых текстов и что не трогать в esim-bot-texts.json, чтобы не затереть изменения.\n\nАндрей Комисаренко",
    attachments: [{ filename: NAME, path: file }] };
  if (DRY) return console.log("[без отправки]", o.to, "|", o.subject, "\n" + o.text);
  const r = await sendMail(o);
  if (r && r.ok) fs.writeFileSync(FLAG, JSON.stringify({ at: Date.now() }));
  console.log(r && r.ok ? "отправлено Петрову" : "не ушло: " + (r && r.error));
})().catch((e) => { console.error("petrov bot notice:", e.message); process.exit(1); });
